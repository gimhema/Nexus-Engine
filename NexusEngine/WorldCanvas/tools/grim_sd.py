def P(c, *xy, dx=0, dy=0):
    """채운 다각형 한 줄 — 좌표쌍을 (dx, dy) 만큼 옮겨서."""
    return f"    poly {c} " + " ".join(f"{x + dx} {y + dy}" for x, y in xy)


def L_(c, x0, y0, x1, y1, dx=0, dy=0):
    return f"    line {x0 + dx} {y0 + dy} {x1 + dx} {y1 + dy} {c}"


def tatters(x0, x1, y, phase, depth=8, step=5):
    """찢어진 단 — 오른쪽에서 왼쪽으로 길고 짧은 날이 섞인다. phase 로 바람에 엇갈림."""
    pattern = [0, depth, 2, depth - 3, 1, depth + 2, 0, depth - 1]
    out = []
    for i, x in enumerate(range(x1, x0 - 1, -step)):
        out.append((x, y + pattern[(i + phase) % len(pattern)]))
    return out


