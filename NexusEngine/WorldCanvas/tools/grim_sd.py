def braid(x, y0, n, b, dx=0):
    """땋은 머리 — 다이아몬드 마디를 아래로 (각진 화풍). 마디마다 왼쪽 위가 밝다."""
    out = []
    for i in range(n):
        cx, cy = x + round(dx * i), y0 + i * 5
        out += [P("h", (cx, cy), (cx + 3, cy + 3), (cx, cy + 6), (cx - 3, cy + 3), dy=b),
                L_("H", cx - 2, cy + 3, cx, cy + 1, dy=b)]
    end = (x + round(dx * n), y0 + n * 5)
    out += [P("h", (end[0] - 1, end[1]), (end[0] + 1, end[1]), (end[0], end[1] + 5), dy=b),
            P("m", (end[0] - 2, end[1] - 1), (end[0] + 2, end[1] - 1), (end[0] + 2, end[1] + 1), (end[0] - 2, end[1] + 1), dy=b)]
    return out


