def pauldron(x, sign, b):
    """각진 견갑 — 바깥으로 뻗는 날. sign -1 왼쪽 / 1 오른쪽 (오른쪽은 그늘 면이 넓다)."""
    def X(v):
        return x + sign * v
    lit, mid, dark = ("A", "B", "C") if sign < 0 else ("B", "C", "Q")
    k = 0.8 if FEMALE else 1.0  # 여자는 견갑이 작고 날이 짧다

    def K(v):
        return X(round(v * k))
    return [P(mid, (X(0), 56), (K(14), 58), (K(18), 54), (K(16), 66), (K(10), 72), (X(0), 70), dy=b),
            P(lit, (X(0), 56), (K(14), 58), (K(10), 62), (X(0), 62), dy=b),
            L_(dark, X(1), 66, K(12), 67, dy=b), L_("R" if sign < 0 else "B", X(1), 56, K(13), 58, dy=b),
            f"    px {K(5)} {64 + b} G"]


